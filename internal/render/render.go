// Package render turns advisor output into text, JSON and config files.
package render

import (
	"fmt"
	"sort"
	"strings"
	"time"

	"github.com/mirastacklabs-ai/kerneltuner/internal/advisor"
	"github.com/mirastacklabs-ai/kerneltuner/internal/facts"
	"github.com/mirastacklabs-ai/kerneltuner/internal/workload"
)

// Meta carries what the renderers need besides the recommendations.
type Meta struct {
	Version  string
	Date     time.Time // zero means now (UTC)
	Facts    *facts.Facts
	Workload *workload.Workload
	// Cites resolves recommendations to their citations. Nil falls back to
	// the bare URLs in Recommendation.Sources.
	Cites *Citations
	// NoCitations drops footnote markers and the References section from the
	// text and markdown reports (scan --no-citations).
	NoCitations bool
}

func (m Meta) date() string {
	d := m.Date
	if d.IsZero() {
		d = time.Now()
	}
	return d.UTC().Format("2006-01-02")
}

func (m Meta) version() string {
	if m.Version == "" {
		return "dev"
	}
	return m.Version
}

// header returns the standard generated-file banner, each line prefixed with
// prefix (e.g. "# ").
func (m Meta) header(prefix string) string {
	lines := []string{
		fmt.Sprintf("Generated by kerneltuner %s on %s", m.version(), m.date()),
		"Review before applying: these are recommendations, not verified for your workload.",
	}
	var b strings.Builder
	for _, l := range lines {
		b.WriteString(prefix + l + "\n")
	}
	return b.String()
}

// Shown reports whether a recommendation appears in default (non --all) output.
func Shown(r advisor.Recommendation) bool {
	switch r.Status {
	case advisor.StatusRecommend, advisor.StatusFiring, advisor.StatusError:
		return true
	}
	return false
}

var domainOrder = []string{"network", "limits", "memory", "cpu", "storage", "ai"}

func domainRank(d string) int {
	for i, x := range domainOrder {
		if x == d {
			return i
		}
	}
	return len(domainOrder)
}

func firstSentence(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if i := strings.Index(s, ". "); i > 0 {
		s = s[:i+1]
	}
	if len(s) > 160 {
		s = s[:157] + "..."
	}
	return s
}

// summaryLines is the host summary, split at " | " so no line exceeds width.
func summaryLines(m Meta, width int) []string {
	var lines []string
	cur := ""
	for _, p := range summaryParts(m) {
		if cur != "" && len(cur)+3+len(p) > width {
			lines = append(lines, cur)
			cur = ""
		}
		if cur != "" {
			cur += " | "
		}
		cur += p
	}
	return append(lines, cur)
}

func summaryParts(m Meta) []string {
	f := m.Facts
	if f == nil {
		return []string{"kerneltuner " + m.version()}
	}
	parts := []string{"kerneltuner " + m.version()}
	if f.Kernel.Release != "" {
		parts = append(parts, "kernel "+f.Kernel.Release)
	}
	if f.CPU.Model != "" || f.CPU.Threads > 0 {
		cpu := f.CPU.Model
		if cpu == "" {
			cpu = f.CPU.Vendor
		}
		parts = append(parts, fmt.Sprintf("CPU %s (%d sockets, %d cores, %d threads)", cpu, f.CPU.Sockets, f.CPU.Cores, f.CPU.Threads))
	}
	if f.Memory.TotalBytes > 0 {
		parts = append(parts, fmt.Sprintf("RAM %.0f GiB", float64(f.Memory.TotalBytes)/(1<<30)))
	}
	parts = append(parts, "accelerators: "+accelSummary(f.Accel))
	parts = append(parts, fmt.Sprintf("Warnings: %d", len(f.Warnings)))
	return parts
}

func accelSummary(a []facts.Accelerator) string {
	if len(a) == 0 {
		return "none"
	}
	count := map[string]int{}
	for _, x := range a {
		count[x.Vendor]++
	}
	var names []string
	for v := range count {
		names = append(names, v)
	}
	sort.Strings(names)
	var parts []string
	for _, v := range names {
		parts = append(parts, fmt.Sprintf("%dx %s", count[v], v))
	}
	return strings.Join(parts, ", ")
}

func change(r advisor.Recommendation) string {
	switch {
	case r.Proposed == "" && r.Current == "":
		return "-"
	case r.Proposed == "" || r.Proposed == r.Current:
		return r.Current
	}
	cur := r.Current
	if cur == "" {
		cur = "(unset)"
	}
	return cur + " -> " + r.Proposed
}

func evidenceText(r advisor.Recommendation) string {
	var parts []string
	for _, e := range r.Evidence {
		parts = append(parts, fmt.Sprintf("%s=%.3g (> %.3g)", e.Metric, e.Value, e.Threshold))
	}
	return strings.Join(parts, "; ")
}
